export function getQuoteForDate(dateStr: string): DailyQuote {
  const parts = dateStr.split('-');
  if (parts.length === 3) {
    const year = parseInt(parts[0], 10);
    const month = parseInt(parts[1], 10) - 1;
    const day = parseInt(parts[2], 10);
    const d = new Date(year, month, day);
    const start = new Date(year, 0, 0);
    const diff = d.getTime() - start.getTime();
    const oneDay = 1000 * 60 * 60 * 24;
    const dayOfYear = Math.floor(diff / oneDay);
    // Unique deterministic rotation for every day of year without repetition
    const index = (dayOfYear + (year % 10) * 17) % QUOTES_COLLECTION.length;
    return QUOTES_COLLECTION[index];
  }
  return QUOTES_COLLECTION[0];
}

export function getRandomDifferentQuote(currentId: number): DailyQuote {
  const filtered = QUOTES_COLLECTION.filter(q => q.id !== currentId);
  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex] || QUOTES_COLLECTION[0];
}

